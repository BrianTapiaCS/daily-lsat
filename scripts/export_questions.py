"""Select about 100 clean questions and write JSON plus a SQL seed."""

from __future__ import annotations

import json
from pathlib import Path

from question_bank import SAMPLE_SIZE, SEED, select_questions

ROOT = Path(__file__).resolve().parents[1]
ELIGIBLE = ROOT / "data" / "processed" / "eligible.json"
SELECTED = ROOT / "data" / "processed" / "selected.json"
SEED_SQL = ROOT / "supabase" / "seed.sql"


def sql_literal(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (dict, list)):
        return "'" + json.dumps(value, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def main() -> None:
    if not ELIGIBLE.exists():
        raise SystemExit("Missing data/processed/eligible.json. Run scripts/validate_questions.py first.")
    eligible = json.loads(ELIGIBLE.read_text(encoding="utf-8"))
    selected = select_questions(eligible, SAMPLE_SIZE, SEED)
    SELECTED.write_text(json.dumps(selected, indent=2), encoding="utf-8")

    values = []
    for row in selected:
        values.append(
            "("
            + ", ".join(
                [
                    sql_literal(row["source_id"]),
                    sql_literal(row["section"]),
                    sql_literal(row["question_type"]),
                    sql_literal(row["difficulty"]),
                    sql_literal(row["scenario"]),
                    sql_literal(row["question_text"]),
                    sql_literal(row["answer_choices"]),
                    sql_literal(row["correct_answer"]),
                    sql_literal(row["explanation"]),
                    sql_literal(row["is_active"]),
                    sql_literal(row["bank_order"]),
                ]
            )
            + ")"
        )

    sql = """-- Generated by scripts/export_questions.py
-- Seed: {seed}. Sample size: {count}.
-- LSAT-style practice questions from ooakdata/lsat-reasoning (CC BY 4.0).
-- Not official LSAC material. Difficulty is null because the source has no difficulty field.

insert into public.questions (
  source_id,
  section,
  question_type,
  difficulty,
  scenario,
  question_text,
  answer_choices,
  correct_answer,
  explanation,
  is_active,
  bank_order
)
values
{values}
on conflict (source_id) do update set
  section = excluded.section,
  question_type = excluded.question_type,
  difficulty = excluded.difficulty,
  scenario = excluded.scenario,
  question_text = excluded.question_text,
  answer_choices = excluded.answer_choices,
  correct_answer = excluded.correct_answer,
  explanation = excluded.explanation,
  is_active = excluded.is_active,
  bank_order = excluded.bank_order;
""".format(seed=SEED, count=len(selected), values=",\n".join(values))
    SEED_SQL.parent.mkdir(parents=True, exist_ok=True)
    SEED_SQL.write_text(sql, encoding="utf-8")
    print(f"selected={len(selected)} json={SELECTED} sql={SEED_SQL}")


if __name__ == "__main__":
    main()
